// @ts-check

import {
  loadDevSignatureSoundSpeechReductionManifest,
  loadOptionalSignatureSoundSpeechReductionReviewAnchor,
} from "./dev-speech-reduction-audio.js"
import { validateSignatureSoundSpeechReductionDeclaration } from "./signature-sound-speech-reduction.js"
import { bindSignatureSoundSpeechReductionReview } from "./signature-sound-speech-reduction-review.js"

const TRAFFIC_BATCH_ID = "batch-21-traffic"
const RETAINED_BATCH_IDS = new Set(["batch-35-london-ambience", "batch-45-stadium-crowd"])
const SPEECH_BATCH_IDS = [TRAFFIC_BATCH_ID, ...RETAINED_BATCH_IDS]

/**
 * Opens each processed concept only from its selected immutable bundle. Traffic
 * uses the reduced-pool v2 render; London and Stadium retain v1 so an already
 * heard decision never migrates to newly generated bytes.
 * @param {{catalog:Record<string,any>,rawDeclaration:unknown,retainedRawDeclaration:unknown,discoveryReview:unknown,anchorPath:string,trafficAnchorPath:string,outputRoot:unknown,trafficOutputRoot:unknown,nodeEnv:string|undefined}} input
 */
export async function applyDevSignatureSoundSpeechReductionReview(input) {
  let entries = input.catalog.entries
  let changed = false
  try {
    const traffic = await loadDevSignatureSoundSpeechReductionBundleForBatch({
      ...input,
      batchId: TRAFFIC_BATCH_ID,
    })
    const bound = bindSignatureSoundSpeechReductionReview({
      reviewEntries: traffic.reviewEntries,
      declaration: traffic.declaration,
      manifest: traffic.snapshot.manifest,
      anchor: traffic.snapshot.anchor,
    })
    entries = replaceSelectedEntries(entries, bound, new Set([TRAFFIC_BATCH_ID]))
    changed = true
  } catch {
    // Fail closed for Traffic without hiding a valid retained London bundle.
  }
  try {
    const retained = await loadDevSignatureSoundSpeechReductionBundleForBatch({
      ...input,
      batchId: "batch-35-london-ambience",
    })
    const bound = bindSignatureSoundSpeechReductionReview({
      reviewEntries: retained.reviewEntries,
      declaration: retained.declaration,
      manifest: retained.snapshot.manifest,
      anchor: retained.snapshot.anchor,
    })
    entries = replaceSelectedEntries(entries, bound, RETAINED_BATCH_IDS)
    changed = true
  } catch {
    // Fail closed for retained concepts without disabling a valid v2 Traffic bundle.
  }
  return changed ? { ...input.catalog, entries } : input.catalog
}

/**
 * Reports only speech-review batches whose exact processed URLs are absent.
 * Persisted decisions for these batches stay valid on disk but must not attach
 * to the raw fallback projection while one immutable bundle is unavailable.
 * @param {{entries:unknown}} catalog
 */
export function selectUnavailableDevSignatureSoundSpeechReductionBatches(catalog) {
  if (!Array.isArray(catalog?.entries)) throw new Error("Speech review catalog entries must be an array")
  const entryByBatch = new Map(catalog.entries.map((entry) => {
    const normalized = requireRecord(entry, "Speech review availability entry")
    return [normalized.batchId, normalized]
  }))
  return SPEECH_BATCH_IDS.filter((batchId) => {
    const entry = entryByBatch.get(batchId)
    if (!entry || !Array.isArray(entry.sources) || entry.sources.length === 0) return true
    const routePrefix = `/api/dev/atmoshaper-candidates/speech-reduction/${batchId}/`
    return entry.sources.some((source) => {
      const normalized = requireRecord(source, "Speech review availability source")
      return typeof normalized.audioUrl !== "string" || !normalized.audioUrl.startsWith(routePrefix)
    })
  })
}

/**
 * Loads the one exact validated bundle that owns a requested batch. The route
 * and page share this decision so their output identities cannot diverge.
 * @param {{batchId:string,catalog:Record<string,any>,rawDeclaration:unknown,retainedRawDeclaration:unknown,discoveryReview:unknown,anchorPath:string,trafficAnchorPath:string,outputRoot:unknown,trafficOutputRoot:unknown,nodeEnv:string|undefined}} input
 */
export async function loadDevSignatureSoundSpeechReductionBundleForBatch(input) {
  const isTraffic = input.batchId === TRAFFIC_BATCH_ID
  if (!isTraffic && !RETAINED_BATCH_IDS.has(input.batchId)) {
    throw new Error("Speech-reduction review batch is unsupported")
  }
  const reviewEntries = isTraffic
    ? input.catalog.entries
    : createRetainedSignatureSoundSpeechReductionReviewEntries({
        reviewEntries: input.catalog.entries,
        retainedRawDeclaration: input.retainedRawDeclaration,
        discoveryReview: input.discoveryReview,
      })
  const rawDeclaration = isTraffic ? input.rawDeclaration : input.retainedRawDeclaration
  const declaration = validateSignatureSoundSpeechReductionDeclaration(rawDeclaration, {
    discoveryReview: input.discoveryReview,
    reviewEntries,
    ...(isTraffic ? {} : { sourceCountOverrides: { [TRAFFIC_BATCH_ID]: 12 } }),
  })
  const anchor = await loadOptionalSignatureSoundSpeechReductionReviewAnchor(
    isTraffic ? input.trafficAnchorPath : input.anchorPath,
  )
  if (!anchor) throw new Error("Speech-reduction review anchor is not committed")
  const outputRoot = isTraffic ? input.trafficOutputRoot : input.outputRoot
  const snapshot = await loadDevSignatureSoundSpeechReductionManifest({
    outputRoot,
    anchor,
    declaration,
    nodeEnv: input.nodeEnv,
  })
  return { declaration, outputRoot, reviewEntries, snapshot }
}

/**
 * Reconstructs only the historical review projection needed to authenticate
 * the immutable v1 declaration. Its Traffic entry is never returned to the
 * live catalog; current Traffic always comes from v2.
 * @param {{reviewEntries:unknown,retainedRawDeclaration:unknown,discoveryReview:unknown}} input
 */
export function createRetainedSignatureSoundSpeechReductionReviewEntries({
  reviewEntries,
  retainedRawDeclaration,
  discoveryReview,
}) {
  if (!Array.isArray(reviewEntries)) throw new Error("Retained speech review entries must be an array")
  const declaration = requireRecord(retainedRawDeclaration, "Retained speech declaration")
  if (!Array.isArray(declaration.concepts)) throw new Error("Retained speech concepts are invalid")
  const traffic = declaration.concepts.find((concept) => (
    concept && typeof concept === "object" && concept.batchId === TRAFFIC_BATCH_ID
  ))
  const normalizedTraffic = requireRecord(traffic, "Retained Traffic declaration")
  if (!Array.isArray(normalizedTraffic.sourceIds)) throw new Error("Retained Traffic sources are invalid")
  const discovery = requireRecord(discoveryReview, "Retained speech discovery")
  if (!Array.isArray(discovery.sources)) throw new Error("Retained speech discovery sources are invalid")
  const sourceById = new Map(discovery.sources.map((source) => {
    const normalized = requireRecord(source, "Retained speech discovery source")
    return [normalized.sourceId, normalized]
  }))
  return reviewEntries.map((entry) => {
    const normalized = requireRecord(entry, "Retained speech review entry")
    if (normalized.batchId !== TRAFFIC_BATCH_ID) return structuredClone(normalized)
    return {
      ...structuredClone(normalized),
      reviewFingerprint: normalizedTraffic.reviewFingerprint,
      sources: normalizedTraffic.sourceIds.map((/** @type {unknown} */ rawSourceId) => {
        if (typeof rawSourceId !== "string") throw new Error("Retained Traffic source id is invalid")
        const sourceId = rawSourceId
        const source = sourceById.get(sourceId)
        if (!source) throw new Error(`Retained Traffic source is missing: ${sourceId}`)
        return structuredClone(source)
      }),
    }
  })
}

/** @param {unknown[]} current @param {unknown[]} replacements @param {Set<string>} batchIds */
function replaceSelectedEntries(current, replacements, batchIds) {
  const replacementByBatch = new Map(replacements.map((entry) => {
    const normalized = requireRecord(entry, "Speech review replacement")
    return [normalized.batchId, normalized]
  }))
  return current.map((entry) => {
    const normalized = requireRecord(entry, "Speech review current entry")
    return batchIds.has(normalized.batchId)
      ? structuredClone(replacementByBatch.get(normalized.batchId) ?? normalized)
      : structuredClone(normalized)
  })
}

/** @param {unknown} value @param {string} label */
function requireRecord(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error(`${label} must be an object`)
  return /** @type {Record<string, any>} */ (value)
}
